-- Keep the legacy join table for existing workspace responses. Persisted roles
-- take precedence in the application; existing explicit roles are preserved.
-- Apply once to an existing PostgreSQL database after reviewing the target.
BEGIN;
CREATE TABLE IF NOT EXISTS project_memberships (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id),
    project_id bigint NOT NULL REFERENCES projects(id),
    role varchar(16) NOT NULL CHECK (role IN ('OWNER', 'MEMBER', 'VIEWER')),
    created_at timestamp,
    updated_at timestamp,
    UNIQUE (user_id, project_id)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_project_memberships_user_project
    ON project_memberships (user_id, project_id);

INSERT INTO project_memberships (user_id, project_id, role, created_at, updated_at)
SELECT owner_id, id, 'OWNER', CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
FROM projects
ON CONFLICT (user_id, project_id) DO NOTHING;

INSERT INTO project_memberships (user_id, project_id, role, created_at, updated_at)
SELECT pm.user_id, pm.project_id,
       CASE WHEN u.role = 'VIEWER' THEN 'VIEWER' ELSE 'MEMBER' END,
       CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
FROM project_members pm
JOIN users u ON u.id = pm.user_id
ON CONFLICT (user_id, project_id) DO NOTHING;

CREATE INDEX IF NOT EXISTS idx_project_memberships_project
    ON project_memberships (project_id);

COMMIT;
